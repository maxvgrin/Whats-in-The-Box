function job = mva_write_osprey_job(T, outDir, cfg)
% Write explicit documented Osprey inputs; Osprey owns format/geometry parsing.
if ~isfolder(outDir), mkdir(outDir); end
job=fullfile(outDir,'osprey_job.m');
fid=fopen(job,'w'); assert(fid>=0,'Cannot write %s',job); closer=onCleanup(@()fclose(fid));
seq='unedited'; targets={'none'};
if isfield(cfg,'seqType'), seq=cfg.seqType; end
if isfield(cfg,'editTarget'), targets=cfg.editTarget; end
fprintf(fid,'%% Generated by What''s in the Box. Localisation uses OspreyCoreg.\n');
fprintf(fid,'seqType = %s;\n',quote(seq)); writecell('editTarget',targets);
fprintf(fid,'dataScenario = ''invivo'';\n');
% Embed the full compatibility block so generated jobs remain standalone.
optionsFile=fullfile(fileparts(mfilename('fullpath')),'resources','osprey','localisation_options.m');
fprintf(fid,'%s\n',fileread(optionsFile));
writecell('files',T.MRS);
fprintf(fid,'%% Separate water references are deliberately ignored for localisation.\n');
writecell('files_ref',{});
writecell('files_nii',T.T1); writecell('files_w',{}); writecell('files_mm',{}); writecell('files_mm_ref',{});
fprintf(fid,'file_stat = '''';\noutputFolder = %s;\n',quote(fullfile(outDir,'osprey')));
    function writecell(key,vals)
        fprintf(fid,'%s = {',key);
        for i=1:numel(vals)
            if i>1, fprintf(fid,', '); end
            fprintf(fid,'%s',quote(vals{i}));
        end
        fprintf(fid,'};\n');
    end
end
function s=quote(s)
s=['''' strrep(char(s),'''','''''') ''''];
end
